/** Best-effort Java → C# for the generated DSA snippets. */
export function javaToCSharp(src) {
  let s = String(src || '');
  s = s.replace(/\r\n/g, '\n');
  s = s.replace(/\bboolean\b/g, 'bool');
  s = s.replace(/\bBoolean\b/g, 'bool');
  s = s.replace(/Integer\.MAX_VALUE/g, 'int.MaxValue');
  s = s.replace(/Integer\.MIN_VALUE/g, 'int.MinValue');
  s = s.replace(/Long\.MAX_VALUE/g, 'long.MaxValue');
  s = s.replace(/Long\.MIN_VALUE/g, 'long.MinValue');
  s = s.replace(/Double\.MAX_VALUE/g, 'double.MaxValue');
  s = s.replace(/Math\.max\(/g, 'Math.Max(');
  s = s.replace(/Math\.min\(/g, 'Math.Min(');
  s = s.replace(/Math\.abs\(/g, 'Math.Abs(');
  s = s.replace(/Math\.sqrt\(/g, 'Math.Sqrt(');
  s = s.replace(/Math\.ceil\(/g, 'Math.Ceiling(');
  s = s.replace(/Math\.floor\(/g, 'Math.Floor(');
  s = s.replace(/Math\.pow\(/g, 'Math.Pow(');
  s = s.replace(/Arrays\.sort\(/g, 'Array.Sort(');
  s = s.replace(/Arrays\.fill\(([^,]+),\s*([^)]+)\)/g, 'Array.Fill($1, $2)');
  s = s.replace(/System\.out\.println\(/g, 'Console.WriteLine(');
  s = s.replace(/HashMap<Integer,\s*Integer>/g, 'Dictionary<int, int>');
  s = s.replace(/HashMap<Integer,\s*List<Integer>>/g, 'Dictionary<int, List<int>>');
  s = s.replace(/HashMap<Character,\s*Integer>/g, 'Dictionary<char, int>');
  s = s.replace(/HashMap<String,\s*Integer>/g, 'Dictionary<string, int>');
  s = s.replace(/HashMap<Integer,\s*Integer\[\]>/g, 'Dictionary<int, int[]>');
  s = s.replace(/HashSet<Integer>/g, 'HashSet<int>');
  s = s.replace(/HashSet<Long>/g, 'HashSet<long>');
  s = s.replace(/HashSet<String>/g, 'HashSet<string>');
  s = s.replace(/HashSet<Character>/g, 'HashSet<char>');
  s = s.replace(/ArrayList<Integer>/g, 'List<int>');
  s = s.replace(/ArrayList<String>/g, 'List<string>');
  s = s.replace(/ArrayList<int\[\]>/g, 'List<int[]>');
  s = s.replace(/List<Integer>/g, 'List<int>');
  s = s.replace(/List<String>/g, 'List<string>');
  s = s.replace(/List<Character>/g, 'List<char>');
  s = s.replace(/List<List<Integer>>/g, 'List<List<int>>');
  s = s.replace(/List<List<String>>/g, 'List<List<string>>');
  s = s.replace(/Queue<Integer>/g, 'Queue<int>');
  s = s.replace(/Queue<int\[\]>/g, 'Queue<int[]>');
  s = s.replace(/Queue<TreeNode>/g, 'Queue<TreeNode>');
  s = s.replace(/Queue<ListNode>/g, 'Queue<ListNode>');
  s = s.replace(/Deque<Integer>/g, 'LinkedList<int>');
  s = s.replace(/Deque<int\[\]>/g, 'LinkedList<int[]>');
  s = s.replace(/Stack<Integer>/g, 'Stack<int>');
  s = s.replace(/Stack<Character>/g, 'Stack<char>');
  s = s.replace(/Stack<TreeNode>/g, 'Stack<TreeNode>');
  s = s.replace(/PriorityQueue<Integer>/g, 'PriorityQueue<int, int>');
  s = s.replace(/PriorityQueue<int\[\]>\s*\([^)]*\)/g, 'PriorityQueue<int[], int>(Comparer<int[]>.Create((a, b) => a[0].CompareTo(b[0]))');
  s = s.replace(/new HashMap<>\(\)/g, 'new Dictionary<int, int>()');
  s = s.replace(/new HashSet<>\(\)/g, 'new HashSet<int>()');
  s = s.replace(/new ArrayList<>\(\)/g, 'new List<int>()');
  s = s.replace(/new LinkedList<>\(\)/g, 'new LinkedList<int>()');
  s = s.replace(/new ArrayDeque<>\(\)/g, 'new LinkedList<int>()');
  s = s.replace(/new Stack<>\(\)/g, 'new Stack<int>()');
  s = s.replace(/new StringBuilder\(\)/g, 'new System.Text.StringBuilder()');
  s = s.replace(/\.append\(/g, '.Append(');
  s = s.replace(/\.toString\(\)/g, '.ToString()');
  s = s.replace(/\.charAt\(/g, '[');
  // charAt(i) -> [i]  (close paren to bracket) — handled loosely below
  s = s.replace(/\.length\(\)/g, '.Length');
  s = s.replace(/\.size\(\)/g, '.Count');
  s = s.replace(/\.isEmpty\(\)/g, '.Count == 0');
  s = s.replace(/\.containsKey\(/g, '.ContainsKey(');
  s = s.replace(/\.contains\(/g, '.Contains(');
  s = s.replace(/\.add\(/g, '.Add(');
  s = s.replace(/\.put\(([^,]+),\s*([^)]+)\)/g, '[$1] = $2');
  s = s.replace(/\.getOrDefault\(([^,]+),\s*([^)]+)\)/g, '.GetValueOrDefault($1, $2)');
  s = s.replace(/\.get\(/g, '[');
  s = s.replace(/\.offer\(/g, '.Enqueue(');
  s = s.replace(/\.poll\(\)/g, '.Dequeue()');
  s = s.replace(/\.peek\(\)/g, '.Peek()');
  s = s.replace(/\.pop\(\)/g, '.Pop()');
  s = s.replace(/\.push\(/g, '.Push(');
  s = s.replace(/\.remove\(/g, '.Remove(');
  s = s.replace(/Character\.isDigit\(/g, 'char.IsDigit(');
  s = s.replace(/Character\.isLetter\(/g, 'char.IsLetter(');
  s = s.replace(/Integer\.parseInt\(/g, 'int.Parse(');
  s = s.replace(/Long\.parseLong\(/g, 'long.Parse(');
  s = s.replace(/String\.valueOf\(/g, '.ToString(/* ');
  s = s.replace(/\bnull\b/g, 'null');
  s = s.replace(/\bString\b/g, 'string');
  s = s.replace(/\bInteger\b/g, 'int');
  s = s.replace(/\bLong\b/g, 'long');
  s = s.replace(/\bCharacter\b/g, 'char');
  s = s.replace(/public class Solution/g, 'public class Solution');
  s = s.replace(/static class /g, 'class ');
  s = s.replace(/\bvoid\b/g, 'void');
  // method names: leave as-is for readability (Java-style names still compile if used consistently)
  s = `using System;\nusing System.Collections.Generic;\nusing System.Linq;\n\n${s}`;
  return s;
}
